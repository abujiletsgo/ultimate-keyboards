inline bool descriptor_matches(const uint8_t* data, size_t size) {
  return data && size == observed_descriptor.size() && std::memcmp(data, observed_descriptor.data(), size) == 0;
}
struct Context { bool built_in = false, exact_product = false, descriptor_matches = false, key_contract_valid = false; };
struct Element {
  uint32_t page = 0xff00, usage = 6, type = 1, report_id = 63;
  bool array = false, relative = false;
  int64_t minimum = 0, maximum = 255;
  uint32_t size_bits = 512, count = 64;
  uint32_t parent_page = 0xff00, parent_usage = 6, parent_type = 513, parent_collection_type = 1;
  bool parent_is_top_level = true;
};
inline bool known_non_key_report(const Context& c, const Element& e) {
  return c.built_in && c.exact_product && c.descriptor_matches && c.key_contract_valid &&
      e.page == 0xff00 && e.usage == 6 && e.type == 1 && e.report_id == 63 && !e.array && !e.relative &&
      e.minimum == 0 && e.maximum == 255 && e.size_bits == 512 && e.count == 64 &&
      e.parent_page == 0xff00 && e.parent_usage == 6 && e.parent_type == 513 &&
      e.parent_collection_type == 1 && e.parent_is_top_level;
}
